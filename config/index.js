/**
 * 请求超时（毫秒）。
 *
 * 【为什么】15 秒是个折中值：
 *   太短（3 秒）——弱网下正常请求也被判失败，用户看到一堆「网络异常」；
 *   太长（60 秒）——真断网时用户要干等一分钟才知道失败。
 *   注意：这个值只管普通业务接口。AI 对话那种要等模型思考的请求，
 *   在 utils/ai.js 里单独给了 60 秒，不能共用这个值。
 */
